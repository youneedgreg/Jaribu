// Builds the header bytes of a JPEG: SOI, a JFIF APP0 segment, extra segments, then a frame
// header. No pixel data: jpegSize never reads that far.
export function fakeJpeg(width: number, height: number, { sof = 0xc0, before = [] as number[][] } = {}): Uint8Array<ArrayBuffer> {
  const app0 = [0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00];
  const frame = [0xff, sof, 0x00, 0x11, 0x08, height >> 8, height & 0xff, width >> 8, width & 0xff, 0x03, 1, 0x22, 0, 2, 0x11, 1, 3, 0x11, 1];
  return new Uint8Array([0xff, 0xd8, ...app0, ...before.flat(), ...frame, 0xff, 0xd9]);
}
